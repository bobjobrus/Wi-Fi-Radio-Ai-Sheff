// Защита от «свиста» (акустической петли) между рациями. Переносимый код (без Arduino) — проверяется на компьютере
// (tests/native_test.cpp).
//
// 30.09.2026 автор прислал видео: две рации в одной комнате, говорит рация 2 — рация 1 через полсекунды начинает
// свистеть на 1800 Гц, свист за 1,5 с вырастает на 33 дБ и обрывается с концом передачи. Это петля: микрофон
// говорящей рации слышит динамик слушающей, звук идёт по кругу (через мост, ≈0,2 с) и на частоте, где петля
// усиливает сильнее всего, нарастает. Так же свистят обычные рации, если стоят рядом.
//
// Что делаем во время передачи (кадр 20 мс, после фильтра низа, до усиления):
//  • ищем в полосе 800–4000 Гц тоны: пик, в полосе ±50 Гц вокруг которого больше SHARE энергии кадра (до двух
//    за кадр — в петле с двумя резонансами свист прыгает между ними); за каждым тоном следим серией (до SERIES
//    сразу): пик гуляет ±WANDER полос (±150 Гц — так гуляет свист с периодом круга), кадры, где сильнее другой
//    тон, серию не рвут, а без тонов вовсе серия живёт MISS кадров;
//  • свист — тон, который всё ещё растёт: после ONSET кадров от начала (атака писка или гласной позади) громкость
//    по 8 последним попаданиям растёт ровно, с наклоном ≥ GROW_SLOPE, и с конца атаки выросла на GROW_NET_DB.
//    Или держится LONG кадров (0,5 с) ярко (> SHARE_LONG энергии) и на месте (±50 Гц; у мелодии соседние ноты
//    попадают в одну серию, но стоят в разных местах): АРУ убавляет усиление,
//    и свист стоит на одном уровне.
//    Проверено на 116 с записей речи рации 1 — ни одного срабатывания; свист на видео находится;
//  • на найденную частоту ставим узкий режекторный фильтр (вырез, Q = NOTCH_Q) — петля на ней больше не усиливает;
//    вырезов до MAX_NOTCH. Вырез от настоящего свиста (растущего или вернувшегося к своему вырезу) держится KEEP_MS
//    (30 мин) — рации обычно так и лежат рядом, а вырез Q6 в речи почти не слышен; вырез только от ровного тона
//    (звонок, писк, долгая нота) — минуту. Свист снова рядом (±150 Гц) с вырезом — петля обходит его по бокам: вырез
//    передвигаем на среднюю частоту и делаем вдвое шире (до Q = 2); серия, начавшаяся рядом с вырезом, отсчитывается
//    от него, и правило «долгий тон» для неё не требует стоять на месте — боковые свисты попадают в одну серию;
//  • нашли растущий свист (или свист вернулся к своему вырезу) — до конца передачи АРУ не прибавляет усиление
//    (hold_agc); ещё одна находка в той же передаче после растущего свиста — та же петля, даже если АРУ уже держит её
//    ровной: микрофон ещё и тише на 6 дБ за раз (петля сильная — рации вплотную, громкость на максимуме). Ровный тон
//    сам по себе (писк прибора, звонок) только вырезается: громкость речи он не трогает.
//    Повторная проверка 30.09 (полная цепочка с АРУ, как в audio.cpp): 576 передач в комнатах с 6 резонансами — без
//    защиты свистят все, с защитой 114; первая передача с одним резонансом — 2 из 294; ложные «тише» — только от
//    долгих насвистанных нот с медленным нарастанием (8 из 658 звуков: ноты, мелодии, гласные, звонки, писки, музыка);
//  • первые SKIP кадров передачи не смотрим: там микрофон слышит свой же «пи-пи» (1400 и 1800 Гц).
#pragma once
#include <stdint.h>

class HowlGuard {
 public:
  static constexpr int N = 320;              // кадр 20 мс при 16 кГц; шаг частот 50 Гц
  static constexpr int K_LO = 16, K_HI = 80; // полоса поиска: 800–4000 Гц
  static constexpr int K_ALL = 5;            // «вся энергия» кадра — от 250 Гц
  static constexpr float SHARE = 0.35f;      // доля энергии кадра в пике (±50 Гц), чтобы считаться тоном
  static constexpr float AMIN = 20.0f;       // тише — не смотрим (шкала 16 бит до усиления)
  static constexpr int SERIES = 3;           // за сколькими тонами следим сразу
  static constexpr int WANDER = 3;           // пик серии гуляет не дальше ±150 Гц от её начала
  static constexpr int MISS = 2;             // кадров без единого тона — и серия кончилась
  static constexpr int STALE = 25;           // тон не появлялся 0,5 с (хоть другие и были) — серия кончилась
  static constexpr int ONSET = 3;            // первые кадры серии — атака звука, рост от них не считаем
  static constexpr float GROW_SLOPE = 0.3f;  // «ещё растёт»: наклон по 8 последним попаданиям ≥ 0,3 дБ на кадр
                                             // (свист на видео — 0,44; у скачущего по громкости ровного тона ≈ 0)
  static constexpr float GROW_NET_DB = 6.0f; // …и с конца атаки вырос всего хотя бы на 6 дБ (свист — на десятки)
  static constexpr int LONG = 25;            // …или держится 25 кадров (0,5 с), причём ярко:
  static constexpr float SHARE_LONG = 0.5f;  // больше половины энергии кадра (ровный тон послабее — не трогаем)
  static constexpr int LONG_SPAN = 2;        // и на месте: ±50 Гц (мелодия, чьи соседние ноты в одной серии, — нет)
  static constexpr int SKIP = 15;            // первые 300 мс передачи — свой сигнал «можно говорить»
  static constexpr int MAX_NOTCH = 4;
  static constexpr float NOTCH_Q = 6.0f;     // полоса выреза ≈ f/6 (1800 Гц → ±150 Гц)
  static constexpr float STEP_DB = 6.0f;     // повторный растущий свист в той же передаче — микрофон тише на столько
  static constexpr float MAX_CUT_DB = 18.0f;
  static constexpr uint32_t KEEP_MS = 30u * 60u * 1000u;   // вырез от настоящего свиста
  static constexpr uint32_t KEEP_STEADY_MS = 60000;        // вырез только от ровного тона (звонок, писк, нота)

  HowlGuard();
  void burst_start(uint32_t now_ms);         // началась передача
  // кадр y[N]: вырезает найденные частоты (на месте) и ищет новый свист. true — только что нашёл
  bool process(float* y, uint32_t now_ms);
  bool hold_agc() const { return hold_; }    // в этой передаче был растущий свист — усиление не поднимать
  float cut_db() const { return cut_db_; }   // насколько убавлен микрофон в этой передаче
  int notches() const { return n_; }
  float notch_hz(int i) const { return hz_[i]; }

 private:
  struct Biquad {
    float b0, b1, b2, a1, a2, x1, x2, y1, y2;
  };
  struct Series {
    bool on, at_notch;
    int ref_k, run, miss, stale, strong;     // strong — попаданий с долей > SHARE_LONG
    int kmin, kmax;                          // где были эти яркие попадания
    float amp[8];                            // амплитуды последних 8 попаданий (по кругу)
    float w, wk;                             // средняя частота (веса — энергия пика)
    float a0;                                // опора роста: громкость сразу после атаки (попадания ONSET…ONSET+2)
  };
  void add_notch(float hz, float q, bool grown, uint32_t now_ms);
  void detected(Series& s, bool grew, uint32_t now_ms);
  float win_[N];
  float cosk_[K_HI + 2];
  Biquad bq_[MAX_NOTCH];
  float hz_[MAX_NOTCH], qz_[MAX_NOTCH];
  bool grown_[MAX_NOTCH];                    // вырез подтверждён настоящим свистом (растущим или вернувшимся к нему)
  uint32_t t_[MAX_NOTCH];                    // когда вырез ставили/подтверждали
  int n_ = 0;
  Series ser_[SERIES];
  int frame_ = 0;
  bool hold_ = false, grew_in_burst_ = false;
  float cut_db_ = 0, atten_ = 1.0f;
};

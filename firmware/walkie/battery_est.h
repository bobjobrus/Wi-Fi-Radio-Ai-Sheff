// Оценка заряда 18650 по замерам напряжения. Переносимый код (без Arduino) — проверяется на компьютере
// (tests/native_test.cpp).
//
// Почему не «замер → проценты» (так было до прошивки 5): напряжение под нагрузкой проседает. При включении
// Wi-Fi подключается на полной мощности, во время разговора работают динамик и кольцо — и замер на это время
// падает на 0,2–0,3 В. 28.09.2026 мост дважды получил ложное «пора на зарядку»: «0 %» и «15 %» в первые
// секунды после включения (заряд был 14–41 %), а за 4 минуты разговора 78 % «превращались» в 70 %.
//
// Правила:
//  • замеры первых WARMUP_MS после включения не в счёт: Wi-Fi подключается и первые 15 с работает без
//    экономии (ECO_IDLE_MS), напряжение гуляет;
//  • во время разговора/приёма и QUIET_MS после них замеры тоже не в счёт (напряжение просажено нагрузкой).
//    Но если рация «занята» дольше MAX_BUSY_MS без единого перерыва (что-то зависло), замеры снова берутся —
//    иначе заряд застыл бы, и о разряде никто бы не узнал. Разговор с паузами так не считается: оценка ждёт
//    первой паузы от 4 с и тогда сразу догоняет;
//  • заряд сообщается (до этого 255 — «измеряется»), когда в окне набралось MIN_SAMPLES спокойных замеров;
//  • оценка — наибольший из последних WINDOW спокойных замеров: просадка напряжение только уменьшает,
//    так что провал короче WINDOW секунд (подсветка, сигнал, всплеск Wi-Fi) отбрасывается целиком, а разряд
//    идёт часами — отставание на 30 с это доли процента. Вверх оценка идёт сразу, вниз — плавно (SMOOTH);
//  • «пора на зарядку» (сигнал и красное кольцо) — только если заряд низкий LOW_HOLD_MS подряд.
#pragma once
#include <stdint.h>

uint8_t battery_pct_from_mv(float mv);    // 0..100 по кривой разряда Li-ion

class BatteryEstimator {
 public:
  static constexpr uint32_t WARMUP_MS = 15000;     // после включения: Wi-Fi подключается, без экономии
  static constexpr uint32_t QUIET_MS = 3000;       // после разговора/приёма — дать напряжению вернуться
  static constexpr uint32_t MAX_BUSY_MS = 300000;  // «занята» 5 мин без перерыва — всё равно мерить
  static constexpr uint32_t LOW_HOLD_MS = 30000;   // «пора на зарядку» — только если низко 30 с подряд
  static constexpr int WINDOW = 30;                // замеров (раз в секунду) в «окне» для наибольшего
  static constexpr int MIN_SAMPLES = 5;            // столько спокойных замеров — и заряд можно сообщать
  static constexpr float SMOOTH = 0.3f;            // доля шага вниз за замер
  static constexpr float NO_BATTERY_MV = 2500;     // ниже — делитель висит в воздухе: питание от USB

  explicit BatteryEstimator(uint8_t low_pct) : low_pct_(low_pct) {}
  // raw_mv — напряжение аккумулятора (уже умноженное на делитель); busy — разговор/приём/обновление/нет Wi-Fi
  void add(float raw_mv, uint32_t now_ms, bool busy);
  uint8_t pct() const;             // 255 — «измеряется» или питание от USB (различает measuring())
  bool measuring() const { return !usb_ && pct() == 255; }
  float mv() const { return pct() == 255 ? 0 : mv_; }
  bool low() const { return low_ && pct() != 255; }   // заряд ≤ low_pct уже LOW_HOLD_MS подряд
  float last_raw() const { return raw_; }

 private:
  uint8_t low_pct_;
  float mv_ = 0, raw_ = 0;
  float win_[WINDOW] = {};
  int win_n_ = 0, win_pos_ = 0;
  bool started_ = false, warm_ = false, usb_ = false;
  uint32_t first_ms_ = 0, busy_ms_ = 0, busy_start_ = 0;   // busy_start — начало «занята» без перерыва
  bool busy_seen_ = false, busy_run_ = false;
  bool low_run_ = false, low_ = false;
  uint32_t low_since_ = 0;
};
